        public static List<LocalizationEntry> ParseLocalization(string text, bool build42)
        {
            if (string.IsNullOrWhiteSpace(text))
                return new();
            if (build42)
            {
                using var document = JsonDocument.Parse(text, new JsonDocumentOptions { AllowTrailingCommas = true, CommentHandling = JsonCommentHandling.Skip });
                if (document.RootElement.ValueKind != JsonValueKind.Object)
                    throw new FormatException("A Build 42 localization file must contain a JSON object.");
                return document.RootElement.EnumerateObject()
                    .Select(x => new LocalizationEntry { Key = x.Name, Value = x.Value.ValueKind == JsonValueKind.String ? x.Value.GetString() ?? "" : x.Value.ToString() })
                    .ToList();
            }

            var body = Regex.Match(text, @"\{(?<body>.*)\}", RegexOptions.Singleline).Groups["body"].Value;
            return Regex.Matches(body, "(?m)^[ \\t]*(?<key>[A-Za-z0-9_.-]+)[ \\t]*=[ \\t]*(?<quote>['\\\"])(?<value>.*?)\\k<quote>[ \\t]*,?[ \\t]*\\r?$")
                .Cast<Match>()
                .Select(x => new LocalizationEntry { Key = x.Groups["key"].Value, Value = UnescapeLua(x.Groups["value"].Value) })
                .ToList();
        }

        public static string BuildLocalization(IEnumerable<LocalizationEntry> entries, bool build42, string category)
        {
            var values = entries.ToList();
            var duplicate = values.GroupBy(x => x.Key.Trim(), StringComparer.Ordinal).FirstOrDefault(x => string.IsNullOrWhiteSpace(x.Key) || x.Count() > 1);
            if (duplicate != null)
                throw new InvalidOperationException(string.IsNullOrWhiteSpace(duplicate.Key) ? "Localization keys cannot be empty." : $"Localization key '{duplicate.Key}' is duplicated.");
            if (build42)
            {
                var ordered = values.ToDictionary(x => x.Key.Trim(), x => x.Value, StringComparer.Ordinal);
                return JsonSerializer.Serialize(ordered, new JsonSerializerOptions { WriteIndented = true }) + Environment.NewLine;
            }

            var sb = new StringBuilder().Append(category).Append("_EN = {").AppendLine();
            foreach (var entry in values)
                sb.Append("    ").Append(entry.Key.Trim()).Append(" = ").Append(Quote(entry.Value)).AppendLine(",");
            return sb.AppendLine("}").ToString();
        }

        public static List<SandboxOptionDefinition> ParseSandboxOptions(string text)
        {
            var result = new List<SandboxOptionDefinition>();
            var matches = Regex.Matches(text, @"\boption\s+(?<id>[A-Za-z_][A-Za-z0-9_.]*)\s*(?:=\s*)?\{", RegexOptions.IgnoreCase);
            foreach (Match match in matches)
            {
                var open = text.IndexOf('{', match.Index + match.Length - 1);
                var close = FindClosingBrace(text, open);
                if (open < 0 || close < 0)
                    continue;
                var option = new SandboxOptionDefinition { Id = match.Groups["id"].Value };
                foreach (var rawProperty in SplitArguments(text[(open + 1)..close]))
                {
                    var property = Regex.Match(rawProperty, @"^\s*(?<key>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?<value>.*?)\s*$", RegexOptions.Singleline);
                    if (property.Success)
                        SetSandboxProperty(option, property.Groups["key"].Value, property.Groups["value"].Value.Trim());
                }
                result.Add(option);
            }
            return result;
        }

        public static string BuildSandboxOptions(IEnumerable<SandboxOptionDefinition> options)
        {
            var values = options.ToList();
            var duplicate = values.GroupBy(x => x.Id.Trim(), StringComparer.OrdinalIgnoreCase).FirstOrDefault(x => string.IsNullOrWhiteSpace(x.Key) || x.Count() > 1);
            if (duplicate != null)
                throw new InvalidOperationException(string.IsNullOrWhiteSpace(duplicate.Key) ? "Sandbox option IDs cannot be empty." : $"Sandbox option '{duplicate.Key}' is duplicated.");
            var sb = new StringBuilder().AppendLine("VERSION = 1,").AppendLine();
            foreach (var item in values)
            {
                if (!Regex.IsMatch(item.Id, @"^[A-Za-z_][A-Za-z0-9_.]*$"))
                    throw new InvalidOperationException($"'{item.Id}' is not a valid sandbox option ID.");
                if (string.IsNullOrWhiteSpace(item.Type))
                    throw new InvalidOperationException($"Sandbox option '{item.Id}' needs a type.");
                sb.Append("option ").Append(item.Id.Trim()).AppendLine(" {");
                AppendSandboxProperty(sb, "type", item.Type);
                AppendSandboxProperty(sb, "default", item.Default);
                AppendSandboxProperty(sb, "min", item.Min);
                AppendSandboxProperty(sb, "max", item.Max);
                AppendSandboxProperty(sb, "step", item.Step);
                AppendSandboxProperty(sb, "numValues", item.NumValues);
                AppendSandboxProperty(sb, "page", item.Page);
                AppendSandboxProperty(sb, "translation", item.Translation);
                AppendSandboxProperty(sb, "tooltip", item.Tooltip);
                AppendSandboxProperty(sb, "valueTranslation", item.ValueTranslation);
                foreach (var extra in item.ExtraProperties.OrderBy(x => x.Key, StringComparer.OrdinalIgnoreCase))
                    AppendSandboxProperty(sb, extra.Key, extra.Value);
                sb.AppendLine("}").AppendLine();
            }
            return sb.ToString();
        }

