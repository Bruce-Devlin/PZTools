        public static IReadOnlyList<string> FindDeclarationFiles(ModTarget target, bool professions)
        {
            if (!Directory.Exists(target.Path))
                return Array.Empty<string>();
            var luaNeedle = professions ? "ProfessionFactory.addProfession" : "TraitFactory.addTrait";
            var scriptNeedle = professions ? "character_profession_definition" : "character_trait_definition";
            return Directory.EnumerateFiles(target.Path, "*", SearchOption.AllDirectories)
                .Where(path => path.EndsWith(".lua", StringComparison.OrdinalIgnoreCase) || path.EndsWith(".txt", StringComparison.OrdinalIgnoreCase))
                .Where(path => File.ReadLines(path).Any(line =>
                    line.Contains(luaNeedle, StringComparison.Ordinal) ||
                    line.Contains(scriptNeedle, StringComparison.OrdinalIgnoreCase)))
                .OrderBy(path => path, StringComparer.OrdinalIgnoreCase)
                .ToList();
        }

        public static List<ProfessionDefinition> ParseProfessions(string text)
        {
            var result = new List<ProfessionDefinition>();
            foreach (var call in FindCalls(text, "ProfessionFactory.addProfession"))
            {
                var args = SplitArguments(call.Arguments);
                if (args.Count < 4)
                    continue;
                var definition = new ProfessionDefinition
                {
                    Id = LuaString(args[0]),
                    TranslationKey = GetTextKey(args[1]),
                    Icon = LuaString(args[2]),
                    Cost = ParseInt(args[3]),
                    DescriptionKey = args.Count > 4 ? GetTextKey(args[4]) : ""
                };
                var variable = FindAssignedVariable(text, call.Start);
                if (!string.IsNullOrWhiteSpace(variable))
                {
                    foreach (Match trait in Regex.Matches(text, $"\\b{Regex.Escape(variable)}\\s*:\\s*addFreeTrait\\s*\\(\\s*(['\\\"])(?<value>.*?)\\1\\s*\\)", RegexOptions.Singleline))
                        if (!IsLineCommented(text, trait.Index))
                            definition.FreeTraits.Add(trait.Groups["value"].Value);
                    AddRecipes(definition.FreeRecipes, text, variable);
                    AddBoosts(definition.XpBoosts, text, variable);
                }
                result.Add(definition);
            }
            foreach (var definition in FindScriptDefinitions(text, "character_profession_definition"))
            {
                var properties = ParseScriptProperties(definition.Body);
                var item = new ProfessionDefinition
                {
                    Id = definition.Id,
                    TranslationKey = ScriptProperty(properties, "UIName"),
                    DescriptionKey = ScriptProperty(properties, "UIDescription"),
                    Icon = ScriptProperty(properties, "IconPathName"),
                    Cost = ParseInt(ScriptProperty(properties, "Cost"))
                };
                AddScriptList(item.FreeTraits, properties, "Traits", "FreeTraits");
                AddScriptList(item.FreeRecipes, properties, "Recipes", "FreeRecipes");
                AddScriptBoosts(item.XpBoosts, properties);
                CopyExtraProperties(item.ExtraProperties, properties,
                    "CharacterProfession", "Cost", "UIName", "UIDescription", "IconPathName", "XPBoosts", "Traits", "FreeTraits", "Recipes", "FreeRecipes");
                result.Add(item);
            }
            return result;
        }

        public static List<TraitDefinition> ParseTraits(string text)
        {
            var result = new List<TraitDefinition>();
            foreach (var call in FindCalls(text, "TraitFactory.addTrait"))
            {
                var args = SplitArguments(call.Arguments);
                if (args.Count < 5)
                    continue;
                var definition = new TraitDefinition
                {
                    Id = LuaString(args[0]),
                    TranslationKey = GetTextKey(args[1]),
                    Cost = ParseInt(args[2]),
                    DescriptionKey = GetTextKey(args[3]),
                    IsProfessionTrait = ParseBool(args[4]),
                    RemoveInMP = args.Count > 5 && ParseBool(args[5])
                };
                var variable = FindAssignedVariable(text, call.Start);
                if (!string.IsNullOrWhiteSpace(variable))
                {
                    AddBoosts(definition.XpBoosts, text, variable);
                    AddRecipes(definition.FreeRecipes, text, variable);
                }
                result.Add(definition);
            }
            foreach (var definition in FindScriptDefinitions(text, "character_trait_definition"))
            {
                var properties = ParseScriptProperties(definition.Body);
                var item = new TraitDefinition
                {
                    Id = definition.Id,
                    TranslationKey = ScriptProperty(properties, "UIName"),
                    DescriptionKey = ScriptProperty(properties, "UIDescription"),
                    Cost = ParseInt(ScriptProperty(properties, "Cost")),
                    IsProfessionTrait = ParseBool(ScriptProperty(properties, "IsProfessionTrait")),
                    RemoveInMP = ParseBool(ScriptProperty(properties, "DisabledInMultiplayer"))
                };
                AddScriptList(item.FreeRecipes, properties, "Recipes", "FreeRecipes");
                AddScriptBoosts(item.XpBoosts, properties);
                CopyExtraProperties(item.ExtraProperties, properties,
                    "CharacterTrait", "Cost", "UIName", "UIDescription", "IsProfessionTrait", "DisabledInMultiplayer", "XPBoosts", "Recipes", "FreeRecipes");
                result.Add(item);
            }
            return result;
        }

