        public static void SaveWithBackup(string path, string content)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path) ?? throw new InvalidOperationException("The file has no parent folder."));
            if (File.Exists(path))
                File.Copy(path, path + ".pztools.bak", true);
            File.WriteAllText(path, content, new UTF8Encoding(false));
        }

        private static StringBuilder NewLuaBuilder(string function) => new StringBuilder()
            .AppendLine(GeneratedHeader).AppendLine()
            .Append("local function ").Append(function).AppendLine("()");

        private static string FinishLuaBuilder(StringBuilder sb, string function) => sb.AppendLine("end").AppendLine()
            .Append("Events.OnGameBoot.Add(").Append(function).AppendLine(")").ToString();

        private static void AddBoosts(ICollection<PerkBoostDefinition> boosts, string text, string variable)
        {
            foreach (Match boost in Regex.Matches(text, $@"\b{Regex.Escape(variable)}\s*:\s*addXPBoost\s*\(\s*Perks\.(?<perk>[A-Za-z_][A-Za-z0-9_]*)\s*,\s*(?<level>-?\d+)\s*\)", RegexOptions.Singleline))
                if (!IsLineCommented(text, boost.Index))
                    boosts.Add(new PerkBoostDefinition { Perk = boost.Groups["perk"].Value, Level = ParseInt(boost.Groups["level"].Value) });
        }

        private static IEnumerable<(string Id, string Body)> FindScriptDefinitions(string text, string keyword)
        {
            foreach (Match match in Regex.Matches(text, $@"\b{Regex.Escape(keyword)}\s+(?<id>[^\s{{]+)\s*\{{", RegexOptions.IgnoreCase))
            {
                if (IsLineCommented(text, match.Index))
                    continue;
                var open = text.IndexOf('{', match.Index + match.Length - 1);
                var close = FindClosingBrace(text, open);
                if (open >= 0 && close > open)
                    yield return (match.Groups["id"].Value.Trim(), text[(open + 1)..close]);
            }
        }

        private static Dictionary<string, string> ParseScriptProperties(string body)
        {
            var properties = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            foreach (Match match in Regex.Matches(body, @"(?m)^\s*(?<key>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?<value>.*?)\s*,?\s*$"))
                properties[match.Groups["key"].Value] = match.Groups["value"].Value.Trim().TrimEnd(',').TrimEnd();
            return properties;
        }

        private static string ScriptProperty(IReadOnlyDictionary<string, string> properties, string key)
            => properties.TryGetValue(key, out var value) ? value : "";

        private static void AddScriptList(ICollection<string> target, IReadOnlyDictionary<string, string> properties, params string[] keys)
        {
            var value = keys.Select(key => ScriptProperty(properties, key)).FirstOrDefault(x => !string.IsNullOrWhiteSpace(x));
            if (string.IsNullOrWhiteSpace(value))
                return;
            foreach (var item in value.Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
                target.Add(item);
        }

        private static void AddScriptBoosts(ICollection<PerkBoostDefinition> target, IReadOnlyDictionary<string, string> properties)
        {
            foreach (var item in ScriptProperty(properties, "XPBoosts").Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            {
                var parts = item.Split('=', 2, StringSplitOptions.TrimEntries);
                if (parts.Length == 2 && int.TryParse(parts[1], NumberStyles.Integer, CultureInfo.InvariantCulture, out var level))
                    target.Add(new PerkBoostDefinition { Perk = parts[0], Level = level });
            }
        }

        private static void CopyExtraProperties(IDictionary<string, string> target, IReadOnlyDictionary<string, string> source, params string[] known)
        {
            var knownSet = known.ToHashSet(StringComparer.OrdinalIgnoreCase);
            foreach (var property in source.Where(x => !knownSet.Contains(x.Key)))
                target[property.Key] = property.Value;
        }

        private static void AppendScriptProperty(StringBuilder sb, string key, string? value)
        {
            if (!string.IsNullOrWhiteSpace(value))
                sb.Append("        ").Append(key).Append(" = ").Append(value.Trim()).AppendLine(",");
        }

        private static void AppendScriptList(StringBuilder sb, string key, IEnumerable<string> values)
        {
            var value = string.Join(';', values.Where(x => !string.IsNullOrWhiteSpace(x)).Select(x => x.Trim()));
            AppendScriptProperty(sb, key, value);
        }

        private static void AppendScriptBoosts(StringBuilder sb, IEnumerable<PerkBoostDefinition> boosts)
            => AppendScriptProperty(sb, "XPBoosts", string.Join(';', boosts.Select(x => $"{ValidatePerk(x.Perk)}={x.Level.ToString(CultureInfo.InvariantCulture)}")));

        private static IEnumerable<(int Start, string Arguments)> FindCalls(string text, string name)
        {
            var offset = 0;
            while ((offset = text.IndexOf(name, offset, StringComparison.Ordinal)) >= 0)
            {
                if (IsLineCommented(text, offset))
                {
                    offset += name.Length;
                    continue;
                }
                var open = text.IndexOf('(', offset + name.Length);
                if (open < 0)
                    yield break;
                var close = FindClosingParenthesis(text, open);
                if (close < 0)
                    yield break;
                yield return (offset, text[(open + 1)..close]);
                offset = close + 1;
            }
        }

        private static int FindClosingParenthesis(string text, int open)
        {
            var depth = 0;
            char quote = '\0';
            var escaped = false;
            for (var i = open; i < text.Length; i++)
            {
                var c = text[i];
                if (quote != '\0')
                {
                    if (escaped)
                        escaped = false;
                    else if (c == '\\')
                        escaped = true;
                    else if (c == quote)
                        quote = '\0';
                    continue;
                }
                if (c is '\'' or '\"')
                {
                    quote = c;
                    continue;
                }
                if (c == '(')
                    depth++;
                else if (c == ')' && --depth == 0)
                    return i;
            }
            return -1;
        }

        private static int FindClosingBrace(string text, int open)
        {
            if (open < 0)
                return -1;
            var depth = 0;
            for (var i = open; i < text.Length; i++)
            {
                if (text[i] == '{')
                    depth++;
                else if (text[i] == '}' && --depth == 0)
                    return i;
            }
            return -1;
        }

        private static void SetSandboxProperty(SandboxOptionDefinition item, string key, string value)
        {
            switch (key.ToLowerInvariant())
            {
                case "type":
                    item.Type = value;
                    break;
                case "default":
                    item.Default = value;
                    break;
                case "min":
                    item.Min = value;
                    break;
                case "max":
                    item.Max = value;
                    break;
                case "step":
                    item.Step = value;
                    break;
                case "numvalues":
                    item.NumValues = value;
                    break;
                case "page":
                    item.Page = value;
                    break;
                case "translation":
                    item.Translation = value;
                    break;
                case "tooltip":
                    item.Tooltip = value;
                    break;
                case "valuetranslation":
                    item.ValueTranslation = value;
                    break;
                default:
                    item.ExtraProperties[key] = value;
                    break;
            }
        }

        private static void AppendSandboxProperty(StringBuilder sb, string key, string? value)
        {
            if (!string.IsNullOrWhiteSpace(value))
                sb.Append("    ").Append(key).Append(" = ").Append(value.Trim()).AppendLine(",");
        }

        private static void AddRecipes(ICollection<string> recipes, string text, string variable)
        {
            foreach (Match recipe in Regex.Matches(text, $"\\b{Regex.Escape(variable)}\\s*:\\s*getFreeRecipes\\s*\\(\\s*\\)\\s*:\\s*add\\s*\\(\\s*(['\\\"])(?<value>.*?)\\1\\s*\\)", RegexOptions.Singleline))
                if (!IsLineCommented(text, recipe.Index))
                    recipes.Add(recipe.Groups["value"].Value);
        }

        private static bool IsLineCommented(string text, int index)
        {
            var lineStart = text.LastIndexOf('\n', Math.Max(0, index - 1)) + 1;
            var comment = text.IndexOf("--", lineStart, StringComparison.Ordinal);
            return comment >= lineStart && comment < index;
        }

        private static List<string> SplitArguments(string args)
        {
            var result = new List<string>();
            var start = 0;
            var depth = 0;
            char quote = '\0';
            var escaped = false;
            for (var i = 0; i < args.Length; i++)
            {
                var c = args[i];
                if (quote != '\0')
                {
                    if (escaped)
                        escaped = false;
                    else if (c == '\\')
                        escaped = true;
                    else if (c == quote)
                        quote = '\0';
                    continue;
                }
                if (c is '\'' or '\"')
                    quote = c;
                else if (c == '(')
                    depth++;
                else if (c == ')')
                    depth--;
                else if (c == ',' && depth == 0)
                {
                    result.Add(args[start..i].Trim());
                    start = i + 1;
                }
            }
            result.Add(args[start..].Trim());
            return result;
        }

        private static string? FindAssignedVariable(string text, int callStart)
        {
            var lineStart = text.LastIndexOf('\n', Math.Max(0, callStart - 1)) + 1;
            var prefix = text[lineStart..callStart];
            var match = Regex.Match(prefix, @"(?:local\s+)?(?<name>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*$");
            return match.Success ? match.Groups["name"].Value : null;
        }

        private static string GetTextKey(string expression)
        {
            var match = Regex.Match(expression, "getText\\s*\\(\\s*(['\\\"])(?<value>.*?)\\1\\s*\\)", RegexOptions.Singleline);
            return match.Success ? match.Groups["value"].Value : LuaString(expression);
        }

        private static string LuaString(string value)
        {
            value = value.Trim();
            return value.Length >= 2 && (value[0] is '\'' or '\"') && value[^1] == value[0] ? UnescapeLua(value[1..^1]) : value;
        }

        private static string UnescapeLua(string value) => value.Replace("\\\"", "\"").Replace("\\'", "'").Replace("\\n", "\n").Replace("\\\\", "\\");
        private static int ParseInt(string value) => int.TryParse(value.Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var parsed) ? parsed : 0;
        private static bool ParseBool(string value) => value.Trim().Equals("true", StringComparison.OrdinalIgnoreCase);
        private static string LuaBool(bool value) => value ? "true" : "false";
        private static string Quote(string value) => $"\"{value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "").Replace("\n", "\\n")}\"";
        private static string SafeId(ModProject project) => string.IsNullOrWhiteSpace(project.ModInfo.Id) ? Regex.Replace(project.Name, "[^A-Za-z0-9_]", "") : Regex.Replace(project.ModInfo.Id, "[^A-Za-z0-9_]", "");
        private static void ValidateId(string value, string kind)
        {
            if (string.IsNullOrWhiteSpace(value))
                throw new InvalidOperationException($"Every {kind} needs an ID.");
        }
        private static void ValidateUniqueIds(IEnumerable<string> ids, string kind)
        {
            var duplicate = ids.GroupBy(x => x?.Trim() ?? "", StringComparer.OrdinalIgnoreCase).FirstOrDefault(x => x.Count() > 1);
            if (duplicate != null)
                throw new InvalidOperationException($"The {kind} ID '{duplicate.Key}' is duplicated.");
        }
        private static string ValidatePerk(string value) => Regex.IsMatch(value ?? "", @"^[A-Za-z_][A-Za-z0-9_]*$") ? value! : throw new InvalidOperationException($"'{value}' is not a valid perk name.");
        private static string ValidateScriptToken(string value, string label) => Regex.IsMatch(value ?? "", @"^[A-Za-z_][A-Za-z0-9_.:-]*$") ? value! : throw new InvalidOperationException($"'{value}' is not a valid {label}.");
        private static string ValidateSegment(string value, string label) => Regex.IsMatch(value ?? "", @"^[A-Za-z0-9_-]+$") ? value! : throw new InvalidOperationException($"The {label} may only contain letters, numbers, underscores, and hyphens.");
    }
