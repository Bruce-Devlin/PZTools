        public static string FindScriptModuleName(string text, string fallback)
        {
            var match = Regex.Match(text ?? "", @"(?im)^\s*module\s+(?<name>[^\s{]+)\s*\{");
            return match.Success ? match.Groups["name"].Value : ValidateScriptToken(fallback, "module name");
        }

        public static string BuildProfessions(IEnumerable<ProfessionDefinition> professions)
        {
            var values = professions.ToList();
            ValidateUniqueIds(values.Select(x => x.Id), "profession");
            var sb = NewLuaBuilder("registerProfessions");
            var index = 0;
            foreach (var item in values)
            {
                ValidateId(item.Id, "profession");
                var variable = $"profession{++index}";
                var description = string.IsNullOrWhiteSpace(item.DescriptionKey) ? "" : $", getText({Quote(item.DescriptionKey)})";
                sb.AppendLine($"    local {variable} = ProfessionFactory.addProfession({Quote(item.Id)}, getText({Quote(item.TranslationKey)}), {Quote(item.Icon)}, {item.Cost.ToString(CultureInfo.InvariantCulture)}{description})");
                foreach (var trait in item.FreeTraits.Where(x => !string.IsNullOrWhiteSpace(x)))
                    sb.AppendLine($"    {variable}:addFreeTrait({Quote(trait.Trim())})");
                foreach (var boost in item.XpBoosts)
                    sb.AppendLine($"    {variable}:addXPBoost(Perks.{ValidatePerk(boost.Perk)}, {boost.Level.ToString(CultureInfo.InvariantCulture)})");
                foreach (var recipe in item.FreeRecipes.Where(x => !string.IsNullOrWhiteSpace(x)))
                    sb.AppendLine($"    {variable}:getFreeRecipes():add({Quote(recipe.Trim())})");
                sb.AppendLine();
            }
            return FinishLuaBuilder(sb, "registerProfessions");
        }

