        private static string BuildProfessionScript(IEnumerable<ProfessionDefinition> professions, string moduleName)
        {
            var values = professions.ToList();
            ValidateUniqueIds(values.Select(x => x.Id), "profession");
            var sb = new StringBuilder().Append("module ").Append(ValidateScriptToken(moduleName, "module name")).AppendLine().AppendLine("{");
            foreach (var item in values)
            {
                ValidateScriptToken(item.Id, "profession ID");
                sb.Append("    character_profession_definition ").AppendLine(item.Id).AppendLine("    {");
                AppendScriptProperty(sb, "CharacterProfession", item.Id);
                AppendScriptProperty(sb, "Cost", item.Cost.ToString(CultureInfo.InvariantCulture));
                AppendScriptProperty(sb, "UIName", item.TranslationKey);
                AppendScriptProperty(sb, "UIDescription", item.DescriptionKey);
                AppendScriptProperty(sb, "IconPathName", item.Icon);
                AppendScriptList(sb, "Traits", item.FreeTraits);
                AppendScriptList(sb, "Recipes", item.FreeRecipes);
                AppendScriptBoosts(sb, item.XpBoosts);
                foreach (var property in item.ExtraProperties)
                    AppendScriptProperty(sb, property.Key, property.Value);
                sb.AppendLine("    }");
            }
            return sb.AppendLine("}").ToString();
        }

